"""The kernel. Four layers, every arrow between them pointing one way.

    declaration  ->  plan  ->  record  ->  run

A declaration knows nothing of a run. A plan reads declarations. A record reads both and cannot reach the
run it records. A run reads all three. That order is not a convention held by habit here - a test walks
the real import graph and fails if any module reaches upward or if any of the four so much as name the
laboratory standing beside them.

Import from the layer when you want to say where a thing lives. Import from `cabaxiom` when you just want to
build something. Both reach the same objects."""

